#  FIGURE 5 — Heatmap del horario 
"""
It represents the final schedule generated by the agent after applying the learned policy (Q-Learning).

Each cell in the heatmap corresponds to a stage at a specific time during the festival.

- X-axis: time slots of the day
- Y-axis: festival stages
- Color: popularity of the assigned artist (or 0 if it is a break)

It provides an overview of how the agent organizes the festival,
showing its strategy for assigning artists and break times.
"""
 
def fig_heatmap_horario(modo="C"):
    # Import the functions needed to load the Q-table and run the environment
    from evaluation.evaluate import cargar_qtable, accion_greedy
    from env.festival_env import FestivalEnv
    
    # For each mode, generate an interactive heatmap with plotly that shows the final schedule generated by the agent after applying the learned policy (Q-Learning).
    print(f"  Generando heatmap modo {modo}...")
 
    # Load the trained Q-table for the corresponding mode
    qtable = cargar_qtable(modo)
    # Set up the festival environment in the appropriate mode
    env = FestivalEnv(mode=modo, seed=42)
    
    # Run the environment in greedy mode (without exploration)
    obs, _ = env.reset()
    done = False
    while not done:
        estado = _discretize(obs) # Discretization of the continuous state for use with the Q-table
        accion = accion_greedy(qtable, estado, env) # Select the best action according to the Q-table
        # Execute the action in the environment
        obs, _, term, trunc, _ = env.step(accion)
        done = term or trunc
 
    # VISUALLY CREATE THE SCHEDULE (matrix)
    n_stages, n_slots = env.schedule_matrix.shape
    
    # import from data_generator the names of the stages
    from env.data_generator import STAGE_NAMES 
    stage_names = STAGE_NAMES[:n_stages]
 
    # Generate time slots from 12:00 to 00:00 (n_slots slots of 60 minutes each)
    slot_labels = []
    for i in range(n_slots):
        total_min = 12 * 60 + i * 60
        slot_labels.append(f"{total_min // 60:02d}:{total_min % 60:02d}")

    # Matrices for the heatmap
    z_matrix = []   # artist's popularity (cell color)
    texto_matrix = []   # text shown inside each cell
 
    for s in range(n_stages):
        fila_z = []
        fila_text = []
        for t in range(n_slots):
            aid = int(env.schedule_matrix[s, t])
            # case 1: when the slot is empty --> BREAK (popularity 0)
            if aid == -1 or aid >= len(env.config["artists"]):
                fila_z.append(0.0)
                fila_text.append("BREAK")
            # case 2: slot occupied by an artist (popularity according to the artist)
            else:
                artista = env.config["artists"][aid]
                fila_z.append(artista["popularity"])
                fila_text.append(f"{artista['name']}<br>pop={artista['popularity']:.2f}")
        z_matrix.append(fila_z)
        texto_matrix.append(fila_text) 
 
    env.close()
 
    # Interactive Heatmap with plotly 
    fig = go.Figure(go.Heatmap(
        z = z_matrix,
        text = texto_matrix,
        texttemplate = "%{text}",
        x = slot_labels,
        y = stage_names,
        colorscale = "Blues",
        zmin = 0.0,
        zmax = 1.0,
        colorbar = dict(title="Popularidad"),
        hovertemplate = "Escenario: %{y}<br>Hora: %{x}<br>%{text}<extra></extra>",
    ))

    # Figure configuration
    fig.update_layout(
        title = f"Horario generado por el agente — Modo {modo}: {NOMBRES.get(modo, '')}",
        xaxis_title = "Franja horaria",
        yaxis_title = "Escenario",
        height = 350,
        font = dict(size=12),
    )

    # Save the figure in results/figures/ as an interactive HTML
    ruta_fig = os.path.join(FIGS_DIR, f"05_heatmap_horario_{modo}.html")
    fig.write_html(ruta_fig)
    print(f"  Guardado: {ruta_fig}")
 
 



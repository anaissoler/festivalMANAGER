# FIGURE 3 — Metrics comparison bars
"""
Compare the average performance of the different modes (A, B, C) against the random policy (baseline)

Three main metrics are analyzed:
    - Total reward (overall agent performance)
    - Average happiness (attendee satisfaction)
    - Average revenue (festival income)

- X-axis: evaluated metrics
- Y-axis: average value of each metric

Allows for visual comparison of trade-offs between strategies
"""
def fig_comparativa_barras():
    # Upload the CSV files for mode evaluation and the random policy
    ruta_eval = os.path.join(RESULTS_DIR, "evaluacion_modos.csv")
    ruta_base = os.path.join(RESULTS_DIR, "baseline_aleatoria.csv")
 
    # If the CSV files do not exist, a warning message is displayed
    if not os.path.exists(ruta_eval):
        print(f"  [¡AVISO!] No encontrado: {ruta_eval}. Ejecuta evaluate.py primero.")
        return
    
    # Upload evaluation data
    df = pd.read_csv(ruta_eval)
 
    # Add baseline if it exists
    if os.path.exists(ruta_base):
        df_base = pd.read_csv(ruta_base)
        df = pd.concat([df, df_base], ignore_index=True)
 
    # Calculate the averages of each metric by each mode
    resumen = df.groupby("modo").agg(
        recompensa = ("recompensa_total", "mean"),
        happiness = ("happiness_media",  "mean"),
        revenue = ("revenue_total",    "mean"),
    ).round(3)
 
    # Bar chart settings
    metricas  = ["recompensa", 
                 "happiness", 
                 "revenue"] 
    
    etiquetas = ["Recompensa media", 
                 "Happiness media", 
                 "Revenue medio"]
    
    modos = list(resumen.index) 
    x = np.arange(len(metricas))
    ancho = 0.8 / len(modos)  # width of each bar
 
    # Create the figure
    fig, ax = plt.subplots(figsize=(10, 5))
 
    # For each mode, draw its corresponding bars
    for i, modo in enumerate(modos):
        color  = COLORES.get(modo, "#888888") # color of the mode (defined above) or gray if not found
        offset = (i - len(modos) / 2 + 0.5) * ancho # to center the bars
        valores = [resumen.loc[modo, m] for m in metricas] # the average values of the metrics
        barras = ax.bar(x + offset, valores, ancho * 0.9,
                         label=NOMBRES.get(modo, modo), color=color, alpha=0.85)
        # To add the value above each bar
        for barra, val in zip(barras, valores):
            ax.text(barra.get_x() + barra.get_width() / 2,
                    barra.get_height() + 0.01,
                    f"{val:.2f}", ha="center", va="bottom", fontsize=8)
 
    # titles, legend and grid
    ax.set_xticks(x)
    ax.set_xticklabels(etiquetas, fontsize=11)
    ax.set_ylabel("Valor medio", fontsize=12)
    ax.set_title("Comparativa de métricas por estrategia", fontsize=13)
    ax.legend(fontsize=10)
    ax.grid(True, axis="y", alpha=0.3)
 
    # Save figure in results/figures/
    ruta_fig = os.path.join(FIGS_DIR, "03_comparativa_barras.png")
    plt.tight_layout()
    plt.savefig(ruta_fig, dpi=150)
    plt.close()
    print(f"  Guardado: {ruta_fig}")
 
 


#  FIGURE 4 — Scatter Revenue vs Happiness
"""
It represents the trade-off between the festival's profitability and attendee satisfaction.

Each point corresponds to an evaluation of a specific mode.

- X-axis: cumulative total revenue (festival revenue)
- Y-axis: average attendee happiness (satisfaction)

It allows you to visualize how each strategy is positioned:
    - More profitable modes tend toward the right
    - More experience-focused modes tend upward
    - The balanced mode seeks a middle ground

Centroids (stars) are included to show the average performance of each strategy.
"""

def fig_scatter_revenue_happiness():
    # Upload the CSV files for mode evaluation and random policy
    ruta_eval = os.path.join(RESULTS_DIR, "evaluacion_modos.csv")
    ruta_base = os.path.join(RESULTS_DIR, "baseline_aleatoria.csv")
 
    # If the CSV files do not exist, a warning message is displayed
    if not os.path.exists(ruta_eval):
        print(f"  [AVISO] No encontrado: {ruta_eval}. Ejecuta evaluate.py primero.")
        return
    
    # Upload evaluation data
    df = pd.read_csv(ruta_eval)
    # Add baseline if it exists
    if os.path.exists(ruta_base):
        df = pd.concat([df, pd.read_csv(ruta_base)], ignore_index=True)
 
    # Create the figure
    fig, ax = plt.subplots(figsize=(8, 6))
 
    # For each mode, draw its corresponding points
    for modo in df["modo"].unique():
        sub = df[df["modo"] == modo]
        color = COLORES.get(modo, "#888888")
        label = NOMBRES.get(modo, modo)
 
        # Individual points
        ax.scatter(sub["revenue_total"], sub["happiness_media"],
                   color=color, alpha=0.65, s=55, label=label)
        # Mode centroid (star)
        ax.scatter(sub["revenue_total"].mean(), sub["happiness_media"].mean(),
                   color=color, s=220, marker="*", zorder=5,
                   edgecolors="white", linewidths=0.5)
        # Add a label next to each centroid for visibility
        ax.annotate(
            modo,
            xy=(sub["revenue_total"].mean(), sub["happiness_media"].mean()),
            xytext=(5, 5), textcoords="offset points",
            fontsize=10, fontweight="bold", color=color,
        )
 
    # titles, legend and grid
    ax.set_xlabel("Revenue normalizado acumulado [0–1 por slot]", fontsize=12)
    ax.set_ylabel("Happiness media [0–1]", fontsize=12)
    ax.set_title("Trade-off Revenue vs Happiness por estrategia", fontsize=13)
    ax.legend(fontsize=10)
    ax.grid(True, alpha=0.3)
 
    # Save figure in results/figures/
    ruta_fig = os.path.join(FIGS_DIR, "04_scatter_revenue_happiness.png")
